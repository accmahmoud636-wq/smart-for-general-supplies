// الاسكانر بيكتب زي الكيبورد: لو لغة الجهاز عربي، «EMP0001» بتوصل «ُ’؛0001» أو «ثةح0001»
// هنا بنرجّع الحروف العربي لمقابلها على الكيبورد الإنجليزي (لوحة Arabic 101)
const MULTI = { 'لا': 'b', 'لإ': 'T', 'لأ': 'G', 'لآ': 'B' };
const MAP = {
  'ض': 'q', 'ص': 'w', 'ث': 'e', 'ق': 'r', 'ف': 't', 'غ': 'y', 'ع': 'u', 'ه': 'i', 'خ': 'o', 'ح': 'p', 'ج': '[', 'د': ']',
  'ش': 'a', 'س': 's', 'ي': 'd', 'ب': 'f', 'ل': 'g', 'ا': 'h', 'ت': 'j', 'ن': 'k', 'م': 'l', 'ك': ';', 'ط': "'",
  'ئ': 'z', 'ء': 'x', 'ؤ': 'c', 'ر': 'v', 'ى': 'n', 'ة': 'm', 'و': ',', 'ز': '.', 'ظ': '/', 'ذ': '`',
  // مع Shift (الحروف الكابيتال)
  'َ': 'Q', 'ً': 'W', 'ُ': 'E', 'ٌ': 'R', 'إ': 'Y', '‘': 'U', '÷': 'I', '×': 'O', '؛': 'P',
  'ِ': 'A', 'ٍ': 'S', 'أ': 'H', 'ـ': 'J', '،': 'K', 'ْ': 'X', 'آ': 'N', '’': 'M', 'ّ': '~', '؟': '?',
  // أرقام عربي/هندي
  '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4', '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9',
  '۰': '0', '۱': '1', '۲': '2', '۳': '3', '۴': '4', '۵': '5', '۶': '6', '۷': '7', '۸': '8', '۹': '9',
};
function fixLayout(s) {
  let v = String(s ?? '').trim();
  if (!/[؀-ۿ‘’×÷]/.test(v)) return v;
  for (const [a, b] of Object.entries(MULTI)) v = v.split(a).join(b);
  return [...v].map(c => MAP[c] ?? c).join('');
}
module.exports = { fixLayout };
